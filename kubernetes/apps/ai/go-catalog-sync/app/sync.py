#!/usr/bin/env python3
"""OpenCode Go catalog + price sync for LiteLLM.

Runs daily as a CronJob:
  1. Fetches the live OpenCode Go model list.
  2. Diffs it against go-catalog.json in the Flux repo -> added/removed models.
  3. Regenerates models/opencode-go.yaml: one LiteLLMModel (litellm-operator)
     for each go-* target in the fallback chains of litellmproxy.yaml, with
     current Go prices.
  4. Commits and pushes changes; Flux applies them and the operator rolls LiteLLM.
  5. Publishes status + change events to MQTT for Home Assistant.
"""
import datetime
import json
import math
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

import paho.mqtt.client as mqtt
import requests
import yaml

GO_MODELS_URL = os.environ.get("GO_MODELS_URL", "https://opencode.ai/inference/go/v1/models")
MODELS_DEV_URL = os.environ.get("MODELS_DEV_URL", "https://models.dev/api.json")
GO_KEY = os.environ.get("OPENCODE_GO_API_KEY", "")
REPO_URL = os.environ.get("GIT_REPO_URL", "")
REPO_BRANCH = os.environ.get("GIT_BRANCH", "main")
LITELLM_DIR = os.environ.get("LITELLM_DIR", "kubernetes/apps/ai/litellm/app")
PROXY_FILE = "litellmproxy.yaml"  # holds the fallback chains (spec.litellmSettings.fallbacks)
GO_MODELS_FILE = "models/opencode-go.yaml"
CATALOG_FILE = "go-catalog.json"
GIT_KEY_FILE = os.environ.get("GIT_KEY_FILE", "/secrets/git/identity")
GIT_KNOWN_HOSTS = os.environ.get("GIT_KNOWN_HOSTS", "/secrets/git/known_hosts")
MQTT_HOST = os.environ.get("MQTT_HOST", "")
MQTT_PORT = int(os.environ.get("MQTT_PORT", "1883"))
MQTT_USER = os.environ.get("MQTT_USER")
MQTT_PASS = os.environ.get("MQTT_PASS")
TOPIC = os.environ.get("MQTT_TOPIC_PREFIX", "homelab/opencode-go")
DRY_RUN = os.environ.get("DRY_RUN") == "1"
MAX_PRICE_RATIO = float(os.environ.get("MAX_PRICE_RATIO", "3.0"))
USER_AGENT = "jaimenet-go-sync/1.0"

EVENT_TYPES = [
    "baseline_created", "models_added", "models_removed", "tracked_model_removed",
    "prices_updated", "price_change_suspicious", "sync_error",
]
COST_KEYS = {  # models.dev-style key (USD per 1M) -> LiteLLM model_info key (USD per token)
    "input": "input_cost_per_token",
    "output": "output_cost_per_token",
    "cache_read": "cache_read_input_token_cost",
    "cache_write": "cache_creation_input_token_cost",
}
GENERATED_HEADER = (
    "# GENERATED by go-catalog-sync (kubernetes/apps/ai/go-catalog-sync). Do not edit by hand.\n"
    "# One LiteLLMModel for each go-* target in the fallbacks of ../litellmproxy.yaml.\n"
    "# Prices are Go's published rates (USD per token), used to estimate allowance usage.\n"
    "# yaml-language-server: $schema=https://k8s-schemas.bjw-s.dev/litellm.home-operations.com/litellmmodel_v1alpha1.json\n"
)


def log(msg):
    print(f"[go-sync] {msg}", flush=True)


# ---------- fetching ----------

def fetch_catalog():
    r = requests.get(
        GO_MODELS_URL,
        headers={"Authorization": f"Bearer {GO_KEY}", "User-Agent": USER_AGENT},
        timeout=30,
    )
    r.raise_for_status()
    data = r.json().get("data", [])
    meta = {m["id"]: m for m in data if isinstance(m, dict) and "id" in m}
    if not meta:
        raise RuntimeError("Go models endpoint returned no models")
    return sorted(meta), meta


def extract_cost(meta):
    """Accept a models.dev-style cost block: {"input": 2.0, "output": 10.0, ...} per 1M."""
    cost = meta.get("cost") or meta.get("pricing") if isinstance(meta, dict) else None
    if not isinstance(cost, dict):
        return None
    try:
        out = {k: float(cost[k]) for k in COST_KEYS if cost.get(k) is not None}
    except (TypeError, ValueError):
        return None
    # float() accepts "nan" and "inf"; a NaN ratio would pass the x3 check in diff_prices.
    if not all(math.isfinite(v) and 0 <= v < 1000 for v in out.values()):
        return None
    return out if "input" in out and "output" in out else None


def fetch_prices(ids, go_meta):
    """Prefer prices from Go's own endpoint; fill gaps from models.dev (opencode-go provider)."""
    prices, source = {}, {}
    for mid in ids:
        c = extract_cost(go_meta.get(mid, {}))
        if c:
            prices[mid], source[mid] = c, "go"
    missing = [m for m in ids if m not in prices]
    if missing:
        try:
            md = requests.get(MODELS_DEV_URL, headers={"User-Agent": USER_AGENT}, timeout=60).json()
            models = (md.get("opencode-go") or {}).get("models", {})
            for mid in missing:
                c = extract_cost(models.get(mid, {}))
                if c:
                    prices[mid], source[mid] = c, "models.dev"
        except Exception as e:  # prices are best effort; the catalog diff still runs
            log(f"models.dev lookup failed: {e}")
    return prices, source


# ---------- repo state ----------

def tracked_models(proxy):
    """go-* targets in the fallback chains of the LiteLLMProxy -> Go model IDs."""
    tracked = set()
    settings = ((proxy or {}).get("spec") or {}).get("litellmSettings") or {}
    for entry in settings.get("fallbacks") or []:
        for targets in entry.values():
            tracked.update(t[3:] for t in targets if t.startswith("go-"))
    return tracked


def current_prices(docs):
    """LiteLLMModel documents -> {Go model ID: model_info cost keys}."""
    out = {}
    for d in docs:
        spec = (d or {}).get("spec") or {}
        model = (spec.get("params") or {}).get("model", "")
        if model.startswith("opencode_go/"):
            out[model.split("/", 1)[1]] = (spec.get("info") or {}).get("extra") or {}
    return out


def to_model_info(cost):
    return {COST_KEYS[k]: round(v / 1_000_000, 12) for k, v in cost.items()}


def build_go_models(tracked, new_prices, old_infos):
    entries = []
    for mid in sorted(tracked):
        spec = {
            "modelName": f"go-{mid}",
            "params": {
                "model": f"opencode_go/{mid}",
                "apiKeyRef": {"name": "opencode-go", "key": "OPENCODE_GO_API_KEY"},
            },
        }
        info = to_model_info(new_prices[mid]) if mid in new_prices else old_infos.get(mid)
        if info:
            spec["info"] = {"extra": info}
        entries.append({
            "apiVersion": "litellm.home-operations.com/v1alpha1",
            "kind": "LiteLLMModel",
            # The operator makes env var names from metadata.name, so no dots there.
            "metadata": {"name": f"go-{mid}".replace(".", "-")},
            "spec": spec,
        })
    return entries


class _IndentedDumper(yaml.SafeDumper):
    """Indent list items under their key, as yamllint and yamlfmt in this repo expect."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def dump_go_models(docs):
    return GENERATED_HEADER + yaml.dump_all(
        docs, Dumper=_IndentedDumper, sort_keys=False, explicit_start=True)


def diff_prices(tracked, new_prices, old_infos):
    """Returns (applied, suspicious) as {mid: (old_info, new_info)}; suspicious ones keep the old price."""
    applied, suspicious = {}, {}
    for mid in sorted(tracked):
        if mid not in new_prices:
            continue
        new, old = to_model_info(new_prices[mid]), old_infos.get(mid) or {}
        if new == old:
            continue
        ratios = [new[k] / old[k] for k in new if old.get(k) and new[k] > 0]
        # A price of 0 or less is a bad source value, never a real rate.
        if any(v <= 0 for v in new.values()) or any(r > MAX_PRICE_RATIO or r < 1 / MAX_PRICE_RATIO for r in ratios):
            suspicious[mid] = (old, new)
        else:
            applied[mid] = (old, new)
    for mid in suspicious:
        del new_prices[mid]
    return applied, suspicious


def fmt_price_change(mid, old, new):
    def per_m(info, k):
        v = info.get(k)
        return "–" if v is None else f"${v * 1_000_000:g}"
    parts = [f"{k.split('_')[0]} {per_m(old, k)}→{per_m(new, k)}"
             for k in ("input_cost_per_token", "output_cost_per_token") if old.get(k) != new.get(k)]
    return f"{mid}: " + (", ".join(parts) if parts else "cache rates changed")


# ---------- git ----------

def git(*args, cwd=None):
    subprocess.run(["git", *args], cwd=cwd, check=True)


def clone_repo(workdir):
    key = pathlib.Path(workdir) / "id_key"
    shutil.copy(GIT_KEY_FILE, key)
    key.chmod(0o600)  # ssh refuses group-readable keys, which a secret mount with fsGroup produces
    os.environ["GIT_SSH_COMMAND"] = (
        f"ssh -i {key} -o IdentitiesOnly=yes -o UserKnownHostsFile={GIT_KNOWN_HOSTS} "
        "-o StrictHostKeyChecking=yes"
    )
    repo = pathlib.Path(workdir) / "repo"
    git("clone", "--depth", "1", "--branch", REPO_BRANCH, REPO_URL, str(repo))
    return repo


def commit_and_push(repo, message):
    git("add", "-A", LITELLM_DIR, cwd=repo)
    if subprocess.run(["git", "diff", "--cached", "--quiet"], cwd=repo).returncode == 0:
        return False
    git("-c", "user.name=go-catalog-sync", "-c", "user.email=go-catalog-sync@jaimenet.com",
        "commit", "-m", message, cwd=repo)
    git("push", "origin", REPO_BRANCH, cwd=repo)
    return True


# ---------- MQTT / Home Assistant ----------

def discovery_messages():
    device = {"identifiers": ["opencode_go_sync"], "name": "OpenCode Go sync", "manufacturer": "homelab"}
    status = f"{TOPIC}/status"
    return [
        ("homeassistant/sensor/opencode_go_models/config", {
            "name": "Model count", "unique_id": "opencode_go_model_count", "icon": "mdi:robot",
            "state_topic": status, "value_template": "{{ value_json.model_count }}",
            "json_attributes_topic": status, "json_attributes_template": "{{ value_json | tojson }}",
            "device": device}, True),
        ("homeassistant/sensor/opencode_go_last_check/config", {
            "name": "Last check", "unique_id": "opencode_go_last_check", "device_class": "timestamp",
            "state_topic": status, "value_template": "{{ value_json.checked_at }}", "device": device}, True),
        ("homeassistant/event/opencode_go_change/config", {
            "name": "Change", "unique_id": "opencode_go_change", "state_topic": f"{TOPIC}/event",
            "event_types": EVENT_TYPES, "device": device}, True),
    ]


def mqtt_publish(messages):
    if not MQTT_HOST:
        log("MQTT_HOST not set, skipping publish")
        return
    client = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2, client_id="go-catalog-sync")
    if MQTT_USER:
        client.username_pw_set(MQTT_USER, MQTT_PASS)
    client.connect(MQTT_HOST, MQTT_PORT, 30)
    client.loop_start()
    try:
        for topic, payload, retain in messages:
            client.publish(topic, json.dumps(payload), qos=1, retain=retain).wait_for_publish(10)
    finally:
        client.loop_stop()
        client.disconnect()


def event(event_type, message, **extra):
    return (f"{TOPIC}/event", {"event_type": event_type, "message": message, **extra}, False)


# ---------- main ----------

def run(repo):
    ldir = repo / LITELLM_DIR
    proxy = yaml.safe_load((ldir / PROXY_FILE).read_text())
    go_models_path, catalog_path = ldir / GO_MODELS_FILE, ldir / CATALOG_FILE
    old_docs = list(yaml.safe_load_all(go_models_path.read_text())) if go_models_path.exists() else []
    old_ids = json.loads(catalog_path.read_text()) if catalog_path.exists() else None

    ids, meta = fetch_catalog()
    tracked = tracked_models(proxy)
    prices, source = fetch_prices(ids, meta)
    old_infos = current_prices(old_docs)
    msgs, commit_lines = [], []

    # catalog diff
    if old_ids is None:
        msgs.append(event("baseline_created", f"Tracking {len(ids)} Go models.", models=ids))
    else:
        added, removed = sorted(set(ids) - set(old_ids)), sorted(set(old_ids) - set(ids))
        if added:
            msgs.append(event("models_added", "New in Go: " + ", ".join(added), models=added))
            commit_lines.append("added: " + ", ".join(added))
        if removed:
            msgs.append(event("models_removed", "Removed from Go: " + ", ".join(removed), models=removed))
            commit_lines.append("removed: " + ", ".join(removed))
    missing_tracked = sorted(tracked - set(ids))
    if missing_tracked:
        msgs.append(event("tracked_model_removed",
                          "In your fallback chains but gone from Go: " + ", ".join(missing_tracked)
                          + f". Update {PROXY_FILE}.", models=missing_tracked))

    # prices
    applied, suspicious = diff_prices(tracked, prices, old_infos)
    if applied:
        lines = [fmt_price_change(m, o, n) for m, (o, n) in applied.items()]
        msgs.append(event("prices_updated", "; ".join(lines), models=sorted(applied)))
        commit_lines += lines
    if suspicious:
        lines = [fmt_price_change(m, o, n) for m, (o, n) in suspicious.items()]
        msgs.append(event("price_change_suspicious",
                          "Not applied (more than x%g change): " % MAX_PRICE_RATIO + "; ".join(lines),
                          models=sorted(suspicious)))
    unpriced = sorted(m for m in tracked if m not in prices and m not in suspicious)
    if unpriced:
        log("no price source for: " + ", ".join(unpriced) + " (keeping previous price or LiteLLM catalog)")

    # write files
    catalog_path.write_text(json.dumps(ids, indent=2) + "\n")
    go_models_path.write_text(dump_go_models(build_go_models(tracked, prices, old_infos)))

    committed = False
    if DRY_RUN:
        log("DRY_RUN: not committing")
    else:
        msg = "chore(litellm): sync OpenCode Go catalog"
        if commit_lines:
            msg += "\n\n" + "\n".join(f"- {line}" for line in commit_lines)
        committed = commit_and_push(repo, msg)

    status = {
        "checked_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "model_count": len(ids), "models": ids, "tracked": sorted(tracked),
        "tracked_missing": missing_tracked, "unpriced": unpriced,
        "price_sources": {m: source[m] for m in sorted(tracked) if m in source},
        "committed": committed,
    }
    mqtt_publish(discovery_messages() + [(f"{TOPIC}/status", status, True)] + msgs)
    for _, payload, _ in msgs:
        log(f"{payload['event_type']}: {payload['message']}")
    log(f"done: {len(ids)} models, {len(tracked)} tracked, committed={committed}")


def main():
    workdir = tempfile.mkdtemp()
    try:
        repo = pathlib.Path(os.environ["LOCAL_REPO"]) if os.environ.get("LOCAL_REPO") else clone_repo(workdir)
        run(repo)
    except Exception as e:
        log(f"ERROR: {e}")
        try:
            mqtt_publish(discovery_messages() + [event("sync_error", f"go-catalog-sync failed: {e}")])
        except Exception as mq:
            log(f"MQTT publish also failed: {mq}")
        sys.exit(1)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


if __name__ == "__main__":
    main()
