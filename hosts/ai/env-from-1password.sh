#!/usr/bin/env bash
# Fill the .env file of each AI host stack from 1Password, then restart the
# stack. Run this from a checkout of this repo, on a machine with the
# 1Password CLI and SSH access to the host.
#
# The compose files in git hold ${VARIABLE} only. The values stay in the item
# "AI Host" of the vault "Home-Ops" and in the .env files on the host (mode
# 600). This script is the only writer of those files.
#
#   ./hosts/ai/env-from-1password.sh            # all stacks
#   ./hosts/ai/env-from-1password.sh phonon-pt-br
#
# Variables: AI_HOST (default root@10.30.50.13), OP_VAULT (Home-Ops),
# OP_ITEM (AI Host).
set -euo pipefail

HOST="${AI_HOST:-root@10.30.50.13}"
VAULT="${OP_VAULT:-Home-Ops}"
ITEM="${OP_ITEM:-AI Host}"

usage() {
    echo "usage: $0 [stack ...]" >&2
    echo "stacks: phonon-pt-br, qweanvoice" >&2
    exit 2
}

[[ "${1:-}" == "-h" || "${1:-}" == "--help" ]] && usage

command -v op >/dev/null || {
    echo "error: the 1Password CLI (op) is not on PATH" >&2
    exit 1
}

op_field() {
    local field="$1"
    local value
    value="$(op item get "$ITEM" --vault "$VAULT" --fields "$field" --reveal 2>/dev/null)" || {
        echo "error: field '$field' not found in item '$ITEM' of vault '$VAULT'" >&2
        echo "create it in the 1Password app, or set OP_ITEM/OP_VAULT" >&2
        exit 1
    }
    printf '%s' "$value"
}

# write_env <stack> <<< "the content of the .env"
write_env() {
    local stack="$1"
    local dir="/opt/stacks/$stack"
    ssh "$HOST" "test -d '$dir'" || {
        echo "error: $dir does not exist on $HOST" >&2
        exit 1
    }
    if ssh "$HOST" "install -m 600 /dev/stdin '$dir/.env'"; then
        echo "$stack: .env written"
    else
        echo "error: cannot write $dir/.env on $HOST" >&2
        exit 1
    fi
}

restart() {
    local stack="$1"
    ssh "$HOST" "cd '/opt/stacks/$stack' && docker compose up -d" >/dev/null
    echo "$stack: stack started"
}

fill_phonon() {
    write_env phonon-pt-br <<EOF
# Written by hosts/ai/env-from-1password.sh. Do not edit this file:
# change the item "$ITEM" in 1Password and run the script again.
HF_TOKEN=$(op_field hf_token)
EOF
    restart phonon-pt-br
}

fill_qweanvoice() {
    write_env qweanvoice <<EOF
# Written by hosts/ai/env-from-1password.sh. Do not edit this file:
# change the item "$ITEM" in 1Password and run the script again.
QWEN_STUDIO_API_KEY=$(op_field qwen_studio_api_key)
EOF
    restart qweanvoice
}

STACKS=("$@")
if [[ ${#STACKS[@]} -eq 0 ]]; then
    STACKS=(phonon-pt-br qweanvoice)
fi

for stack in "${STACKS[@]}"; do
    case "$stack" in
    phonon-pt-br) fill_phonon ;;
    qweanvoice) fill_qweanvoice ;;
    *) echo "error: unknown stack '$stack'" >&2; usage ;;
    esac
done
